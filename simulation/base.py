"""Base data structures for the ALOHA vs CSMA simulation engine."""

from dataclasses import dataclass, field
from enum import Enum
from typing import List, Optional, Tuple


class PacketStatus(str, Enum):
    """Lifecycle statuses for a packet in the network simulation."""
    PENDING = "PENDING"
    SUCCESS = "SUCCESS"
    COLLIDED = "COLLIDED"
    DROPPED = "DROPPED"


class ChannelEventStatus(str, Enum):
    """Statuses for individual transmission attempts on the channel."""
    SUCCESS = "SUCCESS"
    COLLISION = "COLLISION"


@dataclass
class Packet:
    """Represents a data packet transmitted across the shared channel.

    Attributes:
        packet_id: Unique identifier for the packet.
        source_node: Identifier of the node that generated this packet.
        generation_time: Timestamp when the packet was created/arrived at the node.
        attempt_time: Timestamp of the most recent transmission attempt.
        successful_time: Timestamp when transmission completed successfully, or None.
        retry_count: Number of retransmission attempts after collisions.
        status: Current packet status (PENDING, SUCCESS, COLLIDED, DROPPED).
    """
    packet_id: int
    source_node: int
    generation_time: float
    attempt_time: Optional[float] = None
    successful_time: Optional[float] = None
    retry_count: int = 0
    status: str = PacketStatus.PENDING


@dataclass
class Node:
    """Represents a network node attempting to transmit over a shared channel.

    Attributes:
        node_id: Unique node identifier.
        packet_queue: Queue of packets waiting to be transmitted or currently being retried.
        packets_generated: Total number of packets generated by this node.
        packets_successful: Total number of packets successfully delivered by this node.
        packets_collided: Total number of transmission collisions experienced by this node.
        retransmissions: Total number of retransmission attempts made by this node.
        total_delay: Cumulative delay (successful_time - generation_time) for successful packets.
    """
    node_id: int
    packet_queue: List[Packet] = field(default_factory=list)
    packets_generated: int = 0
    packets_successful: int = 0
    packets_collided: int = 0
    retransmissions: int = 0
    total_delay: float = 0.0


@dataclass
class Channel:
    """Represents the shared broadcast channel.

    Attributes:
        events: Chronological log of transmission attempts.
                Each entry is a tuple: (start_time, end_time, node_id, status)
                where status is "SUCCESS" or "COLLISION".
    """
    events: List[Tuple[float, float, int, str]] = field(default_factory=list)

    def log(self, start_time: float, end_time: float, node_id: int, status: str) -> None:
        """Appends a transmission event to the channel event log."""
        self.events.append((round(start_time, 9), round(end_time, 9), node_id, status))
